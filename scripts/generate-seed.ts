/**
 * Regenerates supabase/migrations/20261101000004_seed.sql from the TypeScript defaults.
 * Usage: npx tsx scripts/generate-seed.ts
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { DEFAULT_QUOTES } from "../src/lib/quotes";
import { DEFAULT_SETTINGS } from "../src/lib/settings-defaults";

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;

const quotes = DEFAULT_QUOTES.map((q, i) => `  (${lit(q)}, ${i + 1})`).join(",\n");
const settings = Object.entries(DEFAULT_SETTINGS)
  .map(([k, v]) => `  (${lit(k)}, ${lit(JSON.stringify(v))}::jsonb, true)`)
  .join(",\n");

const sql = `-- =====================================================================
-- دفء — Seed data (generated by scripts/generate-seed.ts — do not edit by hand)
-- =====================================================================

insert into public.roles (key, label_ar, description) values
  ('super_admin', 'مشرف عام', 'صلاحيات كاملة على المنصة'),
  ('admin', 'مشرف', 'إدارة طلبات التبرع والتواصل مع المتبرعين'),
  ('coordinator', 'منسق متطوعين', 'عرض الطلبات المسندة وتحديث معلومات الاستلام')
on conflict (key) do update set label_ar = excluded.label_ar, description = excluded.description;

insert into public.motivational_quotes (text, sort_order) values
${quotes}
on conflict (text) do nothing;

insert into public.site_settings (key, value, is_public) values
${settings}
on conflict (key) do nothing;
`;

writeFileSync(join(__dirname, "../supabase/migrations/20261101000004_seed.sql"), sql);
console.log(`Seed written: ${DEFAULT_QUOTES.length} quotes`);
